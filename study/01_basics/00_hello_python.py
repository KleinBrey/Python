# print() 会把括号中的对象显示到终端。Python 使用缩进表示代码层级，
# 不像 JavaScript 那样依赖大括号；同一层代码应保持相同缩进（惯例是 4 个空格）。
print("你好，Python！")
print("我正在按顺序学习 Python。")

# 井号后是单行注释，不会执行。注释应解释“为什么”，而不只是复述代码。
# 三引号常用于模块、类和函数开头的文档字符串，可被 help() 等工具读取。
print("Python", "简单", "实用", sep=" | ")  # sep 控制多个值之间的分隔符
print("这一行不换行", end=" -> ")  # end 默认是换行符 \n
print("接着输出")

