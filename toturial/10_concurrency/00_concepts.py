"""
==================================================
知识点：同步、异步、并发与并行
==================================================

同步/异步描述任务如何等待结果；并发/并行描述多个任务如何推进。
"""

from time import perf_counter, sleep

def fetch(name: str, delay: float = 0.01) -> str:
    sleep(delay)  # 模拟等待网络；同步时当前执行流只能等待
    return f"{name} 完成"


start = perf_counter()
print(fetch("任务 A"))
print(fetch("任务 B"))
print(f"普通顺序执行约耗时：{perf_counter() - start:.3f} 秒")

# 同步：调用者等当前操作完成再继续。
# 异步：等待期间主动让出执行权，让事件循环推进其他任务。
# 并发：多个任务在一段时间内交错推进，不保证同一时刻真正同时运行。
# 并行：多个任务在同一时刻运行，通常需要多个 CPU 核心/进程。
# I/O 密集（网络、磁盘等待）：threading/asyncio 常见。
# CPU 密集（大量计算）：multiprocessing 常见。

